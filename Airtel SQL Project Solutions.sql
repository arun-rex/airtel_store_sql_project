-- Q11. Find the oldest recharge transaction made by each customer.
SELECT CUSTOMER_ID,
MIN(RECHARGE_DATE) AS FIRST_RECHARGE
FROM RECHARGE_HISTORY
GROUP BY CUSTOMER_ID

-- Q12. Display all customers who have not recharged in the last 60 days.
SELECT CONCAT(C.FIRST_NAME,' ',C.LAST_NAME) AS CUSTOMER_NAME, C.CITY,
C.CUSTOMER_STATUS, R.RECHARGE_DATE AS LAST_RECHARGE_DATE
FROM CUSTOMERS C
INNER JOIN RECHARGE_HISTORY R ON C.CUSTOMER_ID = R.CUSTOMER_ID
WHERE DATEDIFF(DAY, CONVERT(DATE, R.RECHARGE_DATE, 23), GETDATE()) >= 60 AND CUSTOMER_STATUS = 'INACTIVE'
ORDER BY CONVERT(DATE, R.RECHARGE_DATE, 23) DESC

-- Q13. Display the number of recharges made in each month of every year.
SELECT YEAR(CONVERT(DATE, R.RECHARGE_DATE, 23)) AS RECHARGE_YEAR,
DATENAME(MONTH, CONVERT(DATE, R.RECHARGE_DATE, 23))AS RECHARGE_MONTH,
COUNT(*) AS TOTAL_RECHARGES
FROM RECHARGE_HISTORY R
GROUP BY YEAR(CONVERT(DATE, R.RECHARGE_DATE, 23)),
DATENAME(MONTH, CONVERT(DATE, R.RECHARGE_DATE, 23))
ORDER BY YEAR(CONVERT(DATE, R.RECHARGE_DATE, 23)),
DATENAME(MONTH, CONVERT(DATE, R.RECHARGE_DATE, 23))

