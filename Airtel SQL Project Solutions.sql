COUNT(*) AS TOTAL_COMPLAINTS
FROM COMPLAINTS
GROUP BY COMPLAINT_TYPE, STATUS
ORDER BY COMPLAINT_TYPE, STATUS

-- Q28. Find the top 3 cities with the weakest average network tower
-- signal strength (Excellent=3, Good=2, Average=1).
SELECT TOP 3 CITY,
AVG(CASE SIGNAL_STRENGTH
WHEN 'Excellent' THEN 3
WHEN 'Good' THEN 2
WHEN 'Average' THEN 1
ELSE 0 END) AS AVG_SIGNAL_SCORE
FROM NETWORK_TOWERS
GROUP BY CITY
ORDER BY AVG_SIGNAL_SCORE ASC

-- Q29. Identify customers who have raised more than 2 complaints.
SELECT CUSTOMER_ID,
COUNT(*) AS TOTAL_COMPLAINTS
FROM COMPLAINTS
GROUP BY CUSTOMER_ID
HAVING COUNT(*) > 2
ORDER BY TOTAL_COMPLAINTS DESC

-- Q30. For each customer, show every recharge along with a running total
-- of their recharges ordered by recharge date.
SELECT CUSTOMER_ID, RECHARGE_DATE, AMOUNT,
SUM(AMOUNT) OVER ( PARTITION BY CUSTOMER_ID
ORDER BY CONVERT(DATE, R.RECHARGE_DATE, 23)
ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
) AS RUNNING_TOTAL
FROM RECHARGE_HISTORY R
ORDER BY CUSTOMER_ID, CONVERT(DATE, R.RECHARGE_DATE, 23)

-- Q31. Create a stored procedure that accepts a complaint status as input
-- and displays the complaint ID, customer name, city, complaint type,
-- status, and complaint date for all matching complaints.
CREATE PROCEDURE SP_COMPLAINTS_BY_STATUS
@STATUS VARCHAR(50)
AS
BEGIN
SELECT CP.COMPLAINT_ID,
CONCAT(C.FIRST_NAME,' ',C.LAST_NAME) AS CUSTOMER_NAME,
C.CITY, CP.COMPLAINT_TYPE, CP.STATUS, CP.COMPLAINT_DATE
FROM COMPLAINTS CP
INNER JOIN CUSTOMERS C ON CP.CUSTOMER_ID = C.CUSTOMER_ID
WHERE CP.STATUS = @STATUS
END

EXEC SP_COMPLAINTS_BY_STATUS 'Open'