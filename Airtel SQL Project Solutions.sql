-- Q6. Show customers who never recharged.
SELECT C.CUSTOMER_ID, C.FIRST_NAME
FROM CUSTOMERS C
LEFT JOIN RECHARGE_HISTORY R ON C.CUSTOMER_ID = R.CUSTOMER_ID
WHERE R.CUSTOMER_ID IS NULL

