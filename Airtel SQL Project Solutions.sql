-- Q25. Create a stored procedure that accepts a customer ID as input
-- and displays the customer's name, plan name, recharge amount, and
-- recharge date.
CREATE PROCEDURE SP_CUSTOMER_RECHARGE_DETAILS
@CUSTOMER_ID INT
AS
BEGIN
SELECT CONCAT(C.FIRST_NAME,' ',C.LAST_NAME) AS CUSTOMER_NAME,
P.PLAN_NAME, R.AMOUNT, R.RECHARGE_DATE
FROM CUSTOMERS C
INNER JOIN PLANS P ON C.PLAN_ID=P.PLAN_ID
INNER JOIN RECHARGE_HISTORY R ON C.CUSTOMER_ID = R.CUSTOMER_ID
WHERE C.CUSTOMER_ID = @CUSTOMER_ID
END

