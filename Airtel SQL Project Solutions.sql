-- TABLE CREATION

CREATE TABLE PLANS(
PLAN_ID INT PRIMARY KEY,
PLAN_NAME VARCHAR(100),
PRICE DECIMAL(10,2),
VALIDITY_DAYS INT,
DATA_GB VARCHAR(50),
NETWORK_5G VARCHAR(10))

CREATE TABLE CUSTOMERS(
CUSTOMER_ID INT PRIMARY KEY,
FIRST_NAME VARCHAR(50),
LAST_NAME VARCHAR(50),
GENDER VARCHAR(20) CHECK(GENDER IN('Male','Female','Others')),
AGE INT CHECK(AGE>=18),
CITY VARCHAR(50),
STATE VARCHAR(50),
JOIN_DATE DATE,
PLAN_ID INT REFERENCES PLANS(PLAN_ID),
CUSTOMER_STATUS VARCHAR(50) CHECK (CUSTOMER_STATUS IN ('Active','Inactive')))

CREATE TABLE RECHARGE_HISTORY(
RECHARGE_ID INT PRIMARY KEY,
CUSTOMER_ID INT,
RECHARGE_DATE VARCHAR(50),
AMOUNT DECIMAL(10,2),
PAYMENT_MODE VARCHAR(30) NOT NULL,
STATUS VARCHAR(20) DEFAULT 'Success')

CREATE TABLE DATA_USAGE(
USAGE_ID INT PRIMARY KEY,
CUSTOMER_ID INT,
USAGE_MONTH VARCHAR(20),
DATA_USAGE_GB DECIMAL(10,2),
CALL_MINUTES INT,
SMS_USED INT)

CREATE TABLE COMPLAINTS(
COMPLAINT_ID INT PRIMARY KEY,
CUSTOMER_ID INT,
COMPLAINT_TYPE VARCHAR(100),
STATUS VARCHAR(50),
COMPLAINT_DATE VARCHAR(20))

CREATE TABLE NETWORK_TOWERS(
TOWER_ID INT PRIMARY KEY,
CITY VARCHAR(50),
NETWORK_TYPE VARCHAR(10),
SIGNAL_STRENGTH VARCHAR(20),
STATUS VARCHAR(20))

