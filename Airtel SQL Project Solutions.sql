-- Q14. Display the customer name, total recharge amount, and categorize
-- each customer as PLATINUM (>=8000), GOLD (5000-7999), SILVER (3000-4999),
-- or BRONZE (<3000). Sort the result by total recharge in descending order.
SELECT C.CUSTOMER_ID, CONCAT(C.FIRST_NAME,' ',C.LAST_NAME) AS CUSTOMER_NAME,
SUM(R.AMOUNT) AS TOTAL_RECHARGE,
CASE
WHEN SUM(R.AMOUNT)>=8000 THEN 'Platinum'
WHEN SUM(R.AMOUNT) BETWEEN 5000 AND 7999 THEN 'Gold'
WHEN SUM(R.AMOUNT) BETWEEN 3000 AND 4999 THEN 'Silver'
ELSE 'Bronze'
END AS CUSTOMER_CATEGORY
FROM CUSTOMERS C
INNER JOIN RECHARGE_HISTORY R ON C.CUSTOMER_ID = R.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.FIRST_NAME, C.LAST_NAME
ORDER BY TOTAL_RECHARGE DESC

